% 类型：函数
% 功能：四元数转方向余弦矩阵
% out：Cbn 方向余弦矩阵
% in：q 四元数

function Cbn = quat2matrix(q)
if size(q,1) == 4
    q2=q.*q;

    Cbn = [q2(1)+q2(2)-q2(3)-q2(4), 2*q(2)*q(3)-2*q(1)*q(4), 2*q(2)*q(4)+2*q(1)*q(3);
         2*q(2)*q(3)+2*q(1)*q(4), q2(1)-q2(2)+q2(3)-q2(4), 2*q(3)*q(4)-2*q(1)*q(2);
         2*q(2)*q(4)-2*q(1)*q(3), 2*q(3)*q(4)+2*q(1)*q(2), q2(1)-q2(2)-q2(3)+q2(4)];  
else
    fprintf('请输入列向量表示的四元数！');
end 
end

